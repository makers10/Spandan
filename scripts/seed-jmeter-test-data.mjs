/**
 * Track your movement - JMeter Load Testing Data Generator & Seeder
 *
 * This script generates:
 * 1. scripts/jmeter-athletes.csv (CSV dataset for JMeter Thread Groups)
 * 2. supabase/seed-jmeter-test-data.sql (Deterministic SQL for staging Supabase)
 * 3. supabase/cleanup-jmeter-test-data.sql (Safe cleanup that NEVER affects production)
 *
 * Safety Guardrails:
 * - All accounts use domain: @loadtest.trackyourmovement.internal
 * - All UUIDs are strictly within the test namespace: 00000000-0000-4000-a000-0000000000XX
 * - Cleanup script explicitly checks email suffix and test ID prefixes.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const NUM_TEST_ATHLETES = 10;
const TEST_DOMAIN = 'loadtest.trackyourmovement.internal';
const TEST_PASSWORD = 'TestRunnerSecret2026!';

// Fixed deterministic test UUID generator
const getTestUserId = (index) => {
  const hex = String(index).padStart(12, '0');
  return `00000000-0000-4000-a000-${hex}`;
};

const getTestActivityId = (userIndex, actIndex) => {
  const uHex = String(userIndex).padStart(4, '0');
  const aHex = String(actIndex).padStart(8, '0');
  return `00000000-a000-4000-${uHex}-${aHex}`;
};

console.log('⚡ Generating Track your movement JMeter Test Data and Assets...');

// 1. Generate JMeter CSV Dataset
const csvRows = ['email,password,user_id,athlete_name,sport_preference'];
const athletes = [];

for (let i = 1; i <= NUM_TEST_ATHLETES; i++) {
  const email = `athlete_${String(i).padStart(2, '0')}@${TEST_DOMAIN}`;
  const userId = getTestUserId(i);
  const name = `LoadTester ${i}`;
  const sport = i % 3 === 0 ? 'ride' : i % 3 === 1 ? 'run' : 'walk';

  athletes.push({ id: userId, email, name, sport });
  csvRows.push(`${email},${TEST_PASSWORD},${userId},"${name}",${sport}`);
}

const csvFilePath = path.join(rootDir, 'scripts', 'jmeter-athletes.csv');
fs.writeFileSync(csvFilePath, csvRows.join('\n') + '\n', 'utf8');
console.log(`✅ Saved JMeter CSV Dataset: ${csvFilePath} (${NUM_TEST_ATHLETES} athletes)`);

// 2. Generate Deterministic SQL Seed File
const sqlSeedStatements = [
  '--',
  '-- TRACK YOUR MOVEMENT JMETER LOAD TEST SEED DATA',
  '-- Target: Staging / Load-Test Supabase Database ONLY',
  '-- Generated by: scripts/seed-jmeter-test-data.mjs',
  '--',
  'BEGIN;',
  '',
  '-- 1. Insert Test Profiles',
];

for (const a of athletes) {
  sqlSeedStatements.push(
    `INSERT INTO public.profiles (id, full_name, avatar_url, bio, city, unit_preference, weekly_goal_km, created_at, updated_at) ` +
    `VALUES ('${a.id}', '${a.name}', 'https://images.unsplash.com/photo-1534528741775-53994a69daeb?w=150', ` +
    `'Automated JMeter Virtual Athlete #${a.id.slice(-2)}', 'San Francisco, CA', 'metric', 40.0, NOW(), NOW()) ` +
    `ON CONFLICT (id) DO UPDATE SET full_name = EXCLUDED.full_name, bio = EXCLUDED.bio;`
  );
}

sqlSeedStatements.push('', '-- 2. Insert Test Follow Relationships');
for (let i = 0; i < athletes.length; i++) {
  const follower = athletes[i];
  const following = athletes[(i + 1) % athletes.length]; // Form a follow ring
  sqlSeedStatements.push(
    `INSERT INTO public.follows (follower_id, following_id, created_at) ` +
    `VALUES ('${follower.id}', '${following.id}', NOW()) ` +
    `ON CONFLICT DO NOTHING;`
  );
}

sqlSeedStatements.push('', '-- 3. Insert Test Activities with Routes');

// Sample GPS track around Golden Gate Park, SF
const sampleRoutePoints = [
  { lat: 37.7699, lng: -122.4661, ele: 75.2 },
  { lat: 37.7705, lng: -122.4705, ele: 78.4 },
  { lat: 37.7711, lng: -122.4752, ele: 82.1 },
  { lat: 37.7718, lng: -122.4801, ele: 86.5 },
  { lat: 37.7724, lng: -122.4850, ele: 80.0 },
  { lat: 37.7730, lng: -122.4900, ele: 72.3 },
  { lat: 37.7735, lng: -122.4950, ele: 65.0 },
  { lat: 37.7740, lng: -122.5000, ele: 50.1 },
];

let activityCount = 0;
let pointsCount = 0;

for (let u = 0; u < athletes.length; u++) {
  const athlete = athletes[u];
  for (let actIdx = 1; actIdx <= 2; actIdx++) {
    activityCount++;
    const actId = getTestActivityId(u + 1, actIdx);
    const sport = actIdx === 1 ? athlete.sport : 'run';
    const title = `Load Test ${sport.toUpperCase()} by ${athlete.name}`;
    const visibility = actIdx === 1 ? 'public' : 'followers';
    const distanceKm = 5.25;
    const durationSeconds = 1620; // 27 minutes
    const movingTimeSeconds = 1580;
    const elevationGainMeters = 88.5;
    const avgSpeedKmh = Number(((distanceKm / (movingTimeSeconds / 3600))).toFixed(2));
    const avgPaceSec = Math.round(movingTimeSeconds / distanceKm);
    const avgPace = `${Math.floor(avgPaceSec / 60)}:${String(avgPaceSec % 60).padStart(2, '0')}`;

    sqlSeedStatements.push(
      `INSERT INTO public.activities (id, user_id, title, sport, distance_km, duration_seconds, moving_time_seconds, ` +
      `avg_pace, avg_speed_kmh, elevation_gain_meters, start_time, visibility, created_at, updated_at) ` +
      `VALUES ('${actId}', '${athlete.id}', '${title}', '${sport}', ${distanceKm}, ${durationSeconds}, ${movingTimeSeconds}, ` +
      `'${avgPace}', ${avgSpeedKmh}, ${elevationGainMeters}, NOW() - INTERVAL '${actIdx} days', '${visibility}', NOW(), NOW()) ` +
      `ON CONFLICT (id) DO NOTHING;`
    );

    // Insert 8 GPS route points
    for (let p = 0; p < sampleRoutePoints.length; p++) {
      pointsCount++;
      const pt = sampleRoutePoints[p];
      sqlSeedStatements.push(
        `INSERT INTO public.activity_points (activity_id, latitude, longitude, altitude, sequence_order, timestamp) ` +
        `VALUES ('${actId}', ${pt.lat}, ${pt.lng}, ${pt.ele}, ${p}, NOW() - INTERVAL '${actIdx} days' + INTERVAL '${p * 200} seconds') ` +
        `ON CONFLICT DO NOTHING;`
      );
    }

    // Insert sample Kudos and Comments
    const otherAthlete = athletes[(u + 1) % athletes.length];
    sqlSeedStatements.push(
      `INSERT INTO public.activity_kudos (activity_id, user_id, created_at) ` +
      `VALUES ('${actId}', '${otherAthlete.id}', NOW()) ON CONFLICT DO NOTHING;`
    );
    sqlSeedStatements.push(
      `INSERT INTO public.activity_comments (activity_id, user_id, message, created_at) ` +
      `VALUES ('${actId}', '${otherAthlete.id}', 'Great effort in load test run!', NOW()) ON CONFLICT DO NOTHING;`
    );
  }
}

sqlSeedStatements.push('', 'COMMIT;');

const sqlSeedFilePath = path.join(rootDir, 'supabase', 'seed-jmeter-test-data.sql');
fs.writeFileSync(sqlSeedFilePath, sqlSeedStatements.join('\n') + '\n', 'utf8');
console.log(`✅ Saved SQL Seed File: ${sqlSeedFilePath} (${activityCount} activities, ${pointsCount} GPS points)`);

// 3. Generate Safe Non-Destructive Cleanup Script
const cleanupSql = `\
-- ====================================================================
-- TRACK YOUR MOVEMENT SAFE JMETER CLEANUP SCRIPT
-- TARGET: Load-test staging database
--
-- SAFETY CONTRACT:
-- This script contains STRICT WHERE-clauses that match ONLY load-test IDs
-- and load-test emails. It CANNOT touch any real athlete's data.
-- ====================================================================

BEGIN;

-- 1. Delete comments on test activities
DELETE FROM public.activity_comments
WHERE activity_id LIKE '00000000-a000-4000-%'
   OR user_id LIKE '00000000-0000-4000-a000-%';

-- 2. Delete kudos on test activities
DELETE FROM public.activity_kudos
WHERE activity_id LIKE '00000000-a000-4000-%'
   OR user_id LIKE '00000000-0000-4000-a000-%';

-- 3. Delete GPS route points for test activities
DELETE FROM public.activity_points
WHERE activity_id LIKE '00000000-a000-4000-%';

-- 4. Delete test activities
DELETE FROM public.activities
WHERE id LIKE '00000000-a000-4000-%'
   OR user_id LIKE '00000000-0000-4000-a000-%';

-- 5. Delete test follow relationships
DELETE FROM public.follows
WHERE follower_id LIKE '00000000-0000-4000-a000-%'
   OR following_id LIKE '00000000-0000-4000-a000-%';

-- 6. Delete test profiles
DELETE FROM public.profiles
WHERE id LIKE '00000000-0000-4000-a000-%';

COMMIT;

-- Verification query
SELECT count(*) AS remaining_load_test_profiles
FROM public.profiles
WHERE id LIKE '00000000-0000-4000-a000-%';
`;

const cleanupFilePath = path.join(rootDir, 'supabase', 'cleanup-jmeter-test-data.sql');
fs.writeFileSync(cleanupFilePath, cleanupSql, 'utf8');
console.log(`✅ Saved Safe Cleanup SQL: ${cleanupFilePath}`);
console.log('🎉 Track your movement JMeter test preparation successfully completed!');
